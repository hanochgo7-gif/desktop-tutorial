"""Single source of truth for the ski-rental discovery questionnaire.

Every question carries both the client-facing text and our internal notes.
build.py renders two pages from this file:
  questionnaire.html     -> for Roy and Omer (no internal notes in the source)
  consultant-guide.html  -> for our team (notes, red flags, teams, deliverables)

Question fields
  id      stable id, e.g. "A-03" (answers are stored under it, never renumber)
  lvl     1 = must (blue piste), 2 = depth (red), 3 = professional (black)
  t       short | long | num | one | many | scale | matrix | poles | list | grid | personas
  q       the question as Roy and Omer see it
  req     required (True/False)
  why     internal: why we need the answer
  hint    client-facing helper text
  more    client-facing follow-up question (rendered as an extra field)
  teams   letters of the expert teams that own the question (see TEAMS)
  flag    internal: red flag / what to challenge when reading the answer
  founders  True -> one answer per founder (Roy, Omer)
  show    {"id": ..., "any": [...]} or {"id": ..., "none": [...]}: conditional display
"""

