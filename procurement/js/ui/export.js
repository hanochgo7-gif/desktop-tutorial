// Export to CSV (UTF-8 with BOM, opens correctly in Excel with Hebrew) and to a real .xlsx (a minimal Office Open XML
// writer: one sheet, right-to-left, numbers stay numbers). Import reads CSV.

function download(blob, name) {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob); a.download = name;
  document.body.append(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(a.href), 2000);
}
const stamp = () => new Date().toISOString().slice(0, 10);

export function toCSV(headers, rows) {
  const esc = (v) => { const s = v === null || v === undefined ? '' : String(v); return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s; };
  return '﻿' + [headers, ...rows].map((r) => r.map(esc).join(',')).join('\r\n');
}
export const downloadCSV = (name, headers, rows) => download(new Blob([toCSV(headers, rows)], { type: 'text/csv;charset=utf-8' }), `${name}-${stamp()}.csv`);

