export function prefetchRoute(pattern, params = {}) {
  let list = [];
  try { list = DATA[pattern]?.(params) || []; } catch { return; } // a prefetch never stops a route
  for (const p of list) p?.catch?.(() => {});
}

const whenIdle = (fn) => (globalThis.requestIdleCallback ? requestIdleCallback(fn, { timeout: 3000 }) : setTimeout(fn, 200));

// ---------- release handoff (perf plan B6, contract C-4) ----------
// With code served from the release cache, a new release waits until the page asks for it. The page asks at a
// change of screen (router.go), after the old view's cleanup and a store flush, and reloads on the new hash, so no
// page ever runs modules from two releases. A tab that sees another tab switch the release reloads at its own next
// change of screen. Nothing happens on the first install, or when the worker activates by itself (it then claims
// the page, which counts as a switch this tab did not ask for).
const release = { reg: null, sw: null, stale: false, requested: false, checked: 0 };
const UPDATE_EVERY_MS = 3_600_000;
export function watchRelease(reg, sw = globalThis.navigator?.serviceWorker, now = Date.now()) {
  if (!reg || !sw || release.reg) return;
  Object.assign(release, { reg, sw, checked: now });
  // A worker that already ran this origin (it controls the page, or a reload bypassed it): its replacement is a new
  // release. Otherwise the first controllerchange is the first install claiming the page.
  let known = Boolean(sw.controller || reg.active);
  sw.addEventListener('controllerchange', () => {
    if (!known) { known = true; return; }
    if (!release.requested) release.stale = true;
  });
}
// The browser checks for a new worker on navigations, which a single-page app seldom makes: check when the learner
// comes back to the tab after more than an hour.
export function checkForRelease(now = Date.now()) {
  if (!release.reg || now - release.checked < UPDATE_EVERY_MS) return false;
  release.checked = now;
  release.reg.update?.()?.catch?.(() => {});
  return true;
}
const releaseDue = () => release.stale || Boolean(release.reg?.waiting && release.sw?.controller);
// Resolves true when this page should reload into the new release: another tab already switched, or the waiting
// worker took over after this page asked (within 3 s; otherwise the page carries on and switches later).
async function switchRelease() {
  if (release.stale) return true;
  const waiting = release.reg?.waiting;
  if (!waiting || !release.sw?.controller) return false;
  release.requested = true;
  const changed = new Promise((resolve) => {
    release.sw.addEventListener('controllerchange', () => resolve(true), { once: true });
    setTimeout(() => resolve(false), 3000);
  });
  try { waiting.postMessage({ type: 'lucid:activate' }); } catch { /* the worker went away */ }
  const ok = await changed;
  release.requested = false;
  if (!ok) return false;
  release.stale = true; // switched: this page now runs the old release under the new worker
  return true;
}
// A hidden tab switches too, but only on a screen that holds nothing in progress: a hub (no parameters, no query,
// not a full-screen activity) with no text typed into it.
const TYPED = 'textarea, input:not([type]), input[type="text"], input[type="search"], [contenteditable=""], [contenteditable="true"]';
export async function releaseOnHide(doc = globalThis.document) {
  const cur = router.current;
  if (!cur || !releaseDue() || cur.extra.bare || cur.pattern.includes(':') || Object.keys(cur.query || {}).length) return false;
  if ([...doc.querySelectorAll(TYPED)].some((el) => el.value || (el.isContentEditable && el.textContent.trim()))) return false;
  if (!(await switchRelease())) return false;
  await store?.flush();
  // Back in view, or moved on meanwhile: the next change of screen reloads instead.
  if (doc.visibilityState !== 'hidden' || router.current !== cur) return false;
  location.reload();
  return true;
}
export const releaseState = () => ({ stale: release.stale, waiting: Boolean(release.reg?.waiting), checked: release.checked });

export const hrefOf = ({ path, query = {} }) => {
  const qs = new URLSearchParams(query).toString();
  return `#/${path}${qs ? `?${qs}` : ''}`;
};

export function navigate(href, { replace = false } = {}) {
  const target = href.startsWith('#') ? href : `#/${href.replace(/^\//, '')}`;
  if (replace) { history.replaceState(null, '', target); router.go(); return; }
  if (location.hash !== target) { location.hash = target; return; }
  router.go();
}

// The top bar of the Hebrew UI speaks Hebrew (SC-9): a content title with no Hebrew letters ("Free writing", a
// scenario's English name) gives way to the name of its section; the page heading below still carries it.
const HEBREW = /[֐-׿]/;
export function topTitle(title, { lang = 'he', section = '' } = {}) {
  const text = String(title || '');
  return lang === 'he' && text && !HEBREW.test(text) && section ? section : text;
}
// The key under which the shell keeps the section-title size across page loads (perf plan B7): the interface
// language, the title's base size and width, its font, and the section names it must fit (a short hash), plus a
// version to bump if the title's styling changes in a way none of these show.
export const TITLE_FIT_VERSION = 1;
export function titleFitKey({ lang = '', base = 0, width = 0, font = '', names = [] } = {}) {
  let h = 0;
  for (const ch of names.join('\u0001')) h = (Math.imul(h, 31) + ch.codePointAt(0)) | 0;
  return `${lang}|${base}|${width}|${font}|${(h >>> 0).toString(36)}|v${TITLE_FIT_VERSION}`;
}
// The section a route belongs to, as [href, label key] from the shell's lists: a lab first (its own entry), then the
// main entry the route lights up, then Settings and Help.
export function sectionOf(route, nav = [], labs = []) {
  const path = route?.path || '';
  const lab = labs.find(([href]) => path === href || path.startsWith(`${href}/`));
  if (lab) return lab;
  const key = route?.extra?.nav || path.split('/')[0];
  return nav.find(([href, , ic]) => ic === key || href === key) || ({ settings: ['settings', 'nav.settings'], help: ['help', 'nav.help'] })[key] || null;
}

export const router = {
  current: null,
  onRoute: null, // set by app: (route) => void
  onTitle: null, // set by app: (route) => void, when a view sets its title
  async go() {
    let { path, query, malformed } = parse();
    if (malformed) { navigate(hasProfile() ? 'today' : 'welcome', { replace: true }); return; }
    if (!path) path = hasProfile() ? 'today' : 'welcome';
    let match = compiled.find((r) => r.re.test(path));
    if (!match) { navigate(hasProfile() ? 'today' : 'welcome', { replace: true }); return; }
    if (!match.extra.public && !hasProfile()) { navigate('welcome', { replace: true }); return; }
    if ((path === 'welcome' || path === 'start') && hasProfile() && !query.again) { navigate('today', { replace: true }); return; }
    const root = document.getElementById('view');
    const seq = ++this.seq;
    const prev = this.current;
    if (prev?.cleanup) { const done = prev.cleanup; prev.cleanup = null; try { done(); } catch (e) { console.error(e); } }
    prev?.unwatch?.forEach((u) => u());
    if (prev) prev.unwatch = [];
    // A new release takes over at a change of screen, after the old view has cleaned up (B6): the page reloads on the
    // new hash instead of importing a view module from the other release.
    if (prev && prev.path !== path && releaseDue()) {
      if (await switchRelease()) { await store.flush(); location.reload(); return; }
      if (seq !== this.seq) return;
    }
    const params = {};
    match.re.exec(path).slice(1).forEach((v, i) => { params[match.keys[i]] = v; });
    preloadRoute(match.pattern);
    prefetchRoute(match.pattern, params);
    const from = prev ? (prev.path === path ? prev.from : hrefOf(prev)) : null; // a query-only change keeps the origin
    const state = { path, pattern: match.pattern, params, query, from, extra: match.extra, unwatch: [], cleanup: null };
    this.current = state;
    this.onRoute?.(state);
    let mod;
    try { mod = await match.load(); } catch (e) {
      console.error(e);
      root.innerHTML = `<div class="empty"><h3>${document.documentElement.lang === 'he' ? 'המסך לא נטען' : 'This screen did not load'}</h3><p>${navigator.onLine ? '' : (document.documentElement.lang === 'he' ? 'אין חיבור לאינטרנט.' : 'You are offline.')}</p><a class="key" href="">${document.documentElement.lang === 'he' ? 'טעינה מחדש' : 'Reload'}</a></div>`;
      return;
    }
    if (this.current !== state) return;
    const ctx = {
      params, query, path, from,
      navigate,
      watch: (colls, fn) => {
        const set = new Set(colls);
        state.unwatch.push(store.on('change', (ev) => { if (this.current === state && ev.colls?.some((c) => set.has(c))) fn(ev); }));
      },
      // The title belongs to the route, so the shell can redraw without losing it (SC-9); the shell decides how
      // it shows in the top bar (onTitle).
      setTitle: (text) => {
        document.title = text ? `${text} · Lucid` : 'Lucid';
        state.title = text || '';
        if (this.current !== state) return;
        if (this.onTitle) this.onTitle(state);
        else { const el = document.getElementById('top-title'); if (el) el.textContent = state.title; }
      },
    };
    root.innerHTML = '<div class="boot"><span class="spinner" role="status" aria-label="…"></span></div>';
    try {
      state.cleanup = (await mod.default(root, ctx)) || null;
    } catch (e) {
      console.error(e);
      root.innerHTML = `<div class="empty"><h3>${document.documentElement.lang === 'he' ? 'משהו השתבש' : 'Something went wrong'}</h3><p class="small faint">${String(e.message || e).replace(/[<>&]/g, '')}</p><a class="key" href="#/today">${document.documentElement.lang === 'he' ? 'חזרה להיום' : 'Back to Today'}</a></div>`;
    }
    if (!query.keepScroll) window.scrollTo(0, 0);
    if (state.extra.bare) root.focus({ preventScroll: true });
    // The likeliest next screen from Today is the next lesson: its modules download while the learner reads.
    if (state.pattern === 'today' && this.current === state) whenIdle(() => preloadRoute('lesson/:id'));
  },
  seq: 0,
  start() {
    addEventListener('hashchange', () => this.go());
    return this.go();
  },
};
