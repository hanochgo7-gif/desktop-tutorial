const compiled = ROUTES.map(([pattern, load, extra = {}]) => {
  const keys = [];
  const re = new RegExp(`^${pattern.replace(/:(\w+)/g, (_, k) => { keys.push(k); return '([^/]+)'; })}$`);
  return { pattern, re, keys, load, extra };
});

// The path is decoded on its own and the query by URLSearchParams, so an encoded "?" or "&" inside a value
// (such as ?next=scenario%2Fx%3Ftab%3Droleplay) stays inside it. A malformed escape in the path (for example
// "#/%E0%A4%A") must not stop the app from starting: it is reported as malformed and the route replaced.
export function parse(hash = location.hash) {
  const h = hash.replace(/^#\/?/, '');
  const i = h.indexOf('?');
  let path = i < 0 ? h : h.slice(0, i);
  try { path = decodeURIComponent(path); } catch { return { path: '', query: {}, malformed: true }; }
  return { path: path.replace(/\/$/, ''), query: Object.fromEntries(new URLSearchParams(i < 0 ? '' : h.slice(i + 1))) };
}

// ---------- what a route needs, fetched as the route resolves (perf plan B2, B3) ----------
// Each route's modules beyond the boot graph (generated by tools/build-route-deps.mjs), as modulepreload links, so
// the view's whole import graph downloads in one round trip instead of one level at a time. Once per module.
const preloaded = new Set();
export function preloadRoute(pattern, doc = globalThis.document) {
  if (!doc?.createElement) return;
  for (const rel of ROUTE_DEPS[pattern] || []) {
    if (preloaded.has(rel)) continue;
    preloaded.add(rel);
    const link = doc.createElement('link');
    link.rel = 'modulepreload';
    link.href = new URL(`../../${rel}`, import.meta.url).href;
    doc.head.append(link);
  }
}
// The content a route's view reads first, started before the view's modules arrive and evaluate. Every call goes
// through content.js, which keeps one promise per file, so the view's own call reuses it (no second request) and
// a failed fetch is forgotten there. The newer per-file methods (contract C-1) are used when content.js has them.
const scenarioList = () => content.scenarioIndex?.() ?? content.scenarios();
const writingList = () => content.writingIndex?.() ?? Promise.all([content.writingExercises(), content.assignments()]);
const center = (kind) => content.center?.(kind);
// The levels a drill draws from: every level up to one above the course level, or every level without one. The same
// rule as pool.drillLevels (tests/unit/router.test.mjs compares them), which the router does not import because
// pool.js is not part of the boot graph.
export const drillLevelsOf = (level = null) => (level ? LEVELS.slice(0, Math.max(0, levelIndex(level)) + 2) : LEVELS);
