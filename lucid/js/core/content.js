// Loads curriculum content (static JSON, cached by the service worker for offline use).
// Lessons are fetched on demand; files that do not exist yet resolve to null.
const base = new URL('../../content/', import.meta.url);
const cache = new Map();

async function get(path, { optional = false } = {}) {
  if (cache.has(path)) return cache.get(path);
  const p = fetch(new URL(path, base)).then(async (r) => {
    if (!r.ok) {
      if (optional && r.status === 404) return null;
      throw new Error(`Could not load ${path} (${r.status})`);
    }
    return r.json();
  }).catch((e) => { cache.delete(path); if (optional) return null; throw e; });
  cache.set(path, p);
  return p;
}

// A file generated by tools/build-content-index.mjs. A 404 is "no such item" (null); any other failure (offline and
// never cached here, or a server error) rejects, and the caller falls back to the full file it was cut from, so a
// device that has only the full files cached still works offline.
async function split(path) {
  const r = await fetch(new URL(path, base));
  if (r.status === 404) return null;
  if (!r.ok) throw new Error(`Could not load ${path} (${r.status})`);
  return r.json();
}
// Memoised promises. A null or failed result is not kept, so the next call tries again (as get() does).
const memo = new Map();
function once(key, load) {
  if (memo.has(key)) return memo.get(key);
  const p = load().then((v) => { if (v == null) memo.delete(key); return v; }, (e) => { memo.delete(key); throw e; });
  memo.set(key, p);
  return p;
}

// The rows of the generated index files: only the fields the lists, Today and the learner model read (contract
// C-11). tools/build-content-index.mjs writes the files with these functions, and the fallbacks below build the
// same rows from the full files, so both ways give the same rows.
const pick = (o, keys) => Object.fromEntries(keys.filter((k) => o[k] !== undefined).map((k) => [k, o[k]]));
export const SCENARIO_ROW = ['id', 'module', 'level', 'title_en', 'title_he', 'goal'];
export const scenarioRow = (s) => ({ ...pick(s, SCENARIO_ROW), n_practice: Array.isArray(s.practice) ? s.practice.length : 0 });
export const WRITING_ROW = ['id', 'stage', 'level', 'kind', 'title_en', 'title_he', 'word_range', 'min_words', 'max_words', 'time_limit_min'];
export const writingRow = (x) => ({ ...pick(x, WRITING_ROW), ...(Array.isArray(x.items) ? { n_items: x.items.length } : {}), ...(x.prompt !== undefined ? { prompt: x.prompt } : {}) });
export const scenarioIndexOf = (data) => (data ? { scenarios: (data.scenarios || []).map(scenarioRow) } : null);
export const writingIndexOf = (ex, as) => (ex || as ? { exercises: (ex?.exercises || []).map(writingRow), assignments: (as?.assignments || []).map(writingRow) } : null);
// A writing-index row for code that still counts task.items (learner model before contract C-11): an empty array
// of the right length, so items.length is the item count and nothing else is read from it.
export const withItemCount = (row) => (row && row.n_items != null && !row.items ? { ...row, items: new Array(row.n_items) } : row);
// The practice centres' files: content/centers/<name>.json holds the exercises of these types.
export const CENTERS = { read: ['read'], listen: ['listen', 'dictation'], speak: ['speak'] };

export const content = {
  taxonomy: () => get('taxonomy.json'),
  curriculum: () => get('curriculum.json'),
  manifest: () => get('manifest.json', { optional: true }),
  lesson: (id) => get(`lessons/${encodeURIComponent(id)}.json`, { optional: true }),
  placement: () => get('placement.json', { optional: true }),
  scenarios: () => get('real-life/scenarios.json', { optional: true }),
  slang: () => get('real-life/slang.json', { optional: true }),
  writingExercises: () => get('writing/exercises.json', { optional: true }),
  assignments: () => get('writing/assignments.json', { optional: true }),
  rubric: () => get('writing/rubric.json', { optional: true }),
  pictures: () => get('pictures.json', { optional: true }),
  // The small generated lists and one file per scenario or task (contract C-1), so a list or one item never downloads
  // every scenario or task. scenario(id) and writingTask(id) resolve to null for an unknown id.
  scenarioIndex() {
    return once('scenarioIndex', () => split('real-life/index.json').catch(() => null)
      .then((d) => d || content.scenarios().then(scenarioIndexOf)));
  },
  scenario(id) {
    return once(`scenario:${id}`, () => split(`real-life/scenario/${encodeURIComponent(id)}.json`)
      .catch(() => content.scenarios().then((d) => d?.scenarios?.find((x) => x.id === id) || null)));
  },
  writingIndex() {
    return once('writingIndex', () => split('writing/index.json').catch(() => null)
      .then((d) => d || Promise.all([content.writingExercises(), content.assignments()]).then(([ex, as]) => writingIndexOf(ex, as))));
  },
  writingTask(id) {
    return once(`writingTask:${id}`, () => split(`writing/task/${encodeURIComponent(id)}.json`)
      .catch(() => Promise.all([content.writingExercises(), content.assignments()])
        .then(([ex, as]) => ex?.exercises?.find((x) => x.id === id) || as?.assignments?.find((x) => x.id === id) || null)));
  },
  // A practice centre's exercises (read, listen, speak) and the auto-graded exercises of one level (drills and level
  // checks). Cached on first use, not precached (contract C-2): each rejects when its file cannot be loaded, and the
  // caller falls back to the lessons on this device (js/ui/center.js, js/core/pool.js).
  center: (name) => get(`centers/${encodeURIComponent(name)}.json`),
  pool: (level) => get(`pool/${encodeURIComponent(level)}.json`),
  // All lessons that exist (manifest lists them; falls back to probing nothing).
  async availableLessons() {
    const m = await this.manifest();
    return new Set(m?.lessons || []);
  },
  async allLessons() {
    const ids = [...(await this.availableLessons())];
    const list = await Promise.all(ids.map((id) => this.lesson(id)));
    return list.filter(Boolean);
  },
};

// Lookup helpers over the taxonomy.
export async function taxonomyIndex() {
  const tx = await content.taxonomy();
  return {
    tx,
    topic: new Map(tx.topics.map((x) => [x.id, x])),
    error: new Map(tx.error_types.map((x) => [x.id, x])),
    level: new Map(tx.levels.map((x) => [x.id, x])),
  };
}
