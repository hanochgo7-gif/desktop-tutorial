// Writes tests/unit/fixtures/release-<RELEASE>.json for tests/unit/compat.test.mjs: for a release that may still be
// running in an open tab, the modules of its tree, what each exports, which of them its page loads at boot (the
// static import graph of js/app.js), and the methods of its `content` object. A tab started on that release keeps
// those modules and opens this release's screens (js/core/compat.js), so the test checks the screens against them.
// The fixture is made once per release from git and never edited by hand.
// Usage (from lucid/, after npm ci --prefix tools/build): node tools/release-fixture.mjs <commit> [--check]
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { join, dirname, posix } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const APP = join(dirname(fileURLToPath(import.meta.url)), '..');
const [commit, flag] = process.argv.slice(2);
if (!commit) { console.error('usage: node tools/release-fixture.mjs <commit> [--check]'); process.exit(2); }
const REPO = join(APP, '..');
const git = (...args) => execFileSync('git', args, { cwd: REPO, encoding: 'utf8', maxBuffer: 64 << 20 });
const short = git('rev-parse', '--short=7', commit).trim();
const release = git('show', `${commit}:lucid/sw.js`).match(/const RELEASE = '([^']+)'/)?.[1];
if (!release) throw new Error(`${commit}: no RELEASE in lucid/sw.js`);

const files = git('ls-tree', '-r', '--name-only', commit, 'lucid').split('\n')
  .map((f) => f.replace(/^lucid\//, ''))
  .filter((f) => f === 'config.js' || /^(js|vendor)\/.+\.m?js$/.test(f)).sort();
const dir = mkdtempSync(join(tmpdir(), 'lucid-fixture-'));
try {
  execFileSync('sh', ['-c', `git archive ${commit} lucid | tar -x -C "${dir}"`], { cwd: REPO });
  const root = join(dir, 'lucid');
  const esbuild = createRequire(join(APP, 'tools/build/package.json'))('esbuild');
  // esbuild's metafile lists each module's exports and static imports exactly as the browser resolves them.
  const meta = (await esbuild.build({
    absWorkingDir: root, entryPoints: files, outdir: join(dir, 'out'), bundle: false, format: 'esm', metafile: true, write: false, logLevel: 'silent',
  })).metafile;
  const exports = {};
  const imports = {};
  for (const out of Object.values(meta.outputs)) {
    if (!out.entryPoint) continue;
    exports[out.entryPoint] = [...out.exports].sort();
  }
  // The static import graph of js/app.js (dynamic imports are the screens, loaded later).
  const graph = (await esbuild.build({
    absWorkingDir: root, entryPoints: ['js/app.js'], outdir: join(dir, 'graph'), bundle: true, splitting: true, format: 'esm', metafile: true, write: false, logLevel: 'silent',
  })).metafile.inputs;
  for (const [f, input] of Object.entries(graph)) imports[f] = input.imports.filter((i) => i.kind === 'import-statement').map((i) => i.path);
  const boot = new Set();
  const visit = (f) => { if (boot.has(f)) return; boot.add(f); for (const i of imports[f] || []) visit(i); };
  visit('js/app.js');
  // The content object's methods, from that release's own content.js.
  globalThis.addEventListener ??= () => {};
  const { content } = await import(pathToFileURL(join(root, 'js/core/content.js')));
  const fixture = {
    release,
    commit: short,
    note: `Generated by tools/release-fixture.mjs from git (${short}) for tests/unit/compat.test.mjs: the modules of release ${release}, what each exports, which of them its page loads at boot, and the methods of its content object.`,
    boot: [...boot].sort(),
    contentMethods: Object.keys(content).filter((k) => typeof content[k] === 'function').sort(),
    exports: Object.fromEntries(Object.keys(exports).sort().map((k) => [k, exports[k]])),
  };
  const text = `${JSON.stringify(fixture, null, 1)}\n`;
  const path = join(APP, 'tests/unit/fixtures', `release-${release}.json`);
  if (flag === '--check') {
    const have = existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : null;
    const same = have && JSON.stringify({ ...have, note: '' }) === JSON.stringify({ ...fixture, note: '' });
    console.log(same ? `${path}: up to date` : `${path}: differs`);
    process.exit(same ? 0 : 1);
  }
  writeFileSync(path, text);
  console.log(`wrote ${path}`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
