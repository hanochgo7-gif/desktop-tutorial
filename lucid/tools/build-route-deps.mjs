// Writes js/core/route-deps.js: for every route in js/core/router.js, the modules its view needs beyond the boot
// graph (everything app.js imports statically, which index.html preloads). The router adds a modulepreload link
// for each one as the route resolves, so a cold screen fetches its whole module graph in one round trip instead
// of one level at a time (perf plan B2, contract C-6). Generated from a static import scan; no bundling, every
// module stays its own file (ADR-1). A stale map only loses speed: import() still resolves every module.
//
// Usage (from lucid/): node tools/build-route-deps.mjs [--check]   --check exits 1 when the committed file is stale.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, posix } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const APP = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = 'js/core/route-deps.js';

// Static imports and re-exports (`import x from '…'`, `import '…'`, `export … from '…'`), never import(). Paths are
// relative to the app root, posix style.
const STATIC = /(?:^|[;\n])\s*(?:import|export)\s*(?:[\w$*{}\s,]*?\s*from\s*)?['"]([^'"]+)['"]/g;
export function staticImports(rel, root = APP) {
  const src = readFileSync(join(root, rel), 'utf8').replace(/^\s*\/\/.*$/gm, '');
  const out = [];
  for (const m of src.matchAll(STATIC)) {
    const spec = m[1];
    if (!spec.startsWith('.')) continue; // bare specifiers do not occur in the app
    out.push(posix.normalize(posix.join(posix.dirname(rel), spec)));
  }
  return out;
}

// Every module reachable from the entries by static imports, entries included, in discovery order.
export function importClosure(entries, root = APP) {
  const seen = new Set();
  const stack = [...entries];
  while (stack.length) {
    const f = stack.shift();
    if (seen.has(f)) continue;
    seen.add(f);
    if (!existsSync(join(root, f))) continue;
    stack.push(...staticImports(f, root));
  }
  return [...seen];
}

// The router's routes: [pattern, view module] in the order they are declared.
export function routesOf(root = APP) {
  const src = readFileSync(join(root, 'js/core/router.js'), 'utf8');
  return [...src.matchAll(/\[\s*'([^']+)'\s*,\s*\(\)\s*=>\s*import\(\s*'([^']+)'\s*\)/g)]
    .map(([, pattern, spec]) => [pattern, posix.normalize(posix.join('js/core', spec))]);
}

// The boot graph: app.js's static closure (index.html's modulepreload list must equal it).
export const bootModules = (root = APP) => importClosure(['js/app.js'], root);

export function buildRouteDeps(root = APP) {
  const boot = new Set(bootModules(root));
  const map = {};
  for (const [pattern, view] of routesOf(root)) map[pattern] = importClosure([view], root).filter((f) => !boot.has(f));
  const lines = Object.entries(map).map(([k, v]) => `  '${k}': [${v.map((f) => `'${f}'`).join(', ')}],`);
  return `// Generated by tools/build-route-deps.mjs from a static import scan; do not edit (run the tool instead).
// For each route: the modules its view needs beyond the boot graph that index.html preloads, as paths from the
// app root. The router preloads them as the route resolves (perf plan B2).
export default {
${lines.join('\n')}
};
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const text = buildRouteDeps();
  const file = join(APP, OUT);
  if (process.argv.includes('--check')) {
    const same = existsSync(file) && readFileSync(file, 'utf8') === text;
    console.log(same ? `${OUT} is up to date` : `${OUT} is stale: run node tools/build-route-deps.mjs`);
    process.exit(same ? 0 : 1);
  }
  writeFileSync(file, text);
  console.log(`${OUT}: ${Object.keys((await import(pathToFileURL(file).href + `?t=${Date.now()}`)).default).length} routes`);
}
